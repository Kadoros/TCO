def _style(ax):
    for s in ax.spines.values():
        s.set_visible(False)
    ax.tick_params(colors=INK2, labelsize=7)


def fig_slices(rows, names, cols_title, kl, out_mode, path, title):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    cmap = LinearSegmentedColormap.from_list("seq", SEQ)
    nr, nc = len(rows), len(rows[0])
    vmax = max(np.abs(M[out_mode]).max() for M in rows[0])
    fig, axes = plt.subplots(nr, nc, figsize=(2.6 * nc, 2.6 * nr), facecolor=SURFACE, squeeze=False)
    for i in range(nr):
        for j in range(nc):
            ax = axes[i, j]
            im = ax.imshow(np.abs(rows[i][j][out_mode]), cmap=cmap, vmin=0, vmax=vmax, origin="lower")
            ax.set_xticks(range(len(kl))); ax.set_xticklabels(kl, fontsize=5)
            ax.set_yticks(range(len(kl))); ax.set_yticklabels(kl, fontsize=5)
            _style(ax)
            if i == 0:
                ax.set_title(cols_title[j], color=INK, fontsize=9)
            if j == 0:
                ax.set_ylabel(names[i], color=INK, fontsize=10)
    cb = fig.colorbar(im, ax=axes, shrink=0.6); cb.outline.set_visible(False); cb.ax.tick_params(colors=INK2, labelsize=7)
    fig.suptitle(title, color=INK, fontsize=11, x=0.01, ha="left")
    fig.savefig(path, dpi=150, facecolor=SURFACE, bbox_inches="tight"); plt.close(fig)


