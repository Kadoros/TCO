# ----------------------------------------------------------------------------- spectral tools
def deriv_np(G):
    n = G.shape[-1]
    k = np.fft.rfftfreq(n, 1.0 / n)
    ik = 1j * k
    if n % 2 == 0:
        ik[-1] = 0
    return np.fft.irfft(ik * np.fft.rfft(G, axis=-1), n, axis=-1)


def deriv_t(G):
    n = G.shape[-1]
    k = torch.fft.rfftfreq(n, 1.0 / n, dtype=G.dtype, device=G.device)
    ik = 1j * k
    if n % 2 == 0:
        ik[-1] = 0
    return torch.fft.irfft(ik * torch.fft.rfft(G, dim=-1), n, dim=-1)


def lowpass_np(G, kmax):
    n = G.shape[-1]
    H = np.fft.rfft(G, axis=-1)
    H[..., kmax + 1:] = 0
    return np.fft.irfft(H, n, axis=-1)


def resample_np(G, n_out):
    """band-limit to |k| < n_out/2 and evaluate on the n_out grid."""
    n = G.shape[-1]
    H = np.fft.rfft(G, axis=-1)[..., : n_out // 2]
    Ho = np.zeros(G.shape[:-1] + (n_out // 2 + 1,), complex)
    Ho[..., : n_out // 2] = H * (n_out / n)
    return np.fft.irfft(Ho, n_out, axis=-1)


# ----------------------------------------------------------------------------- inputs and data
def sample_inputs(rng, n_a, K, nu_range, nu_modes, nu_amp, f_amp):
    """Coefficients in the normalised real Fourier basis (columns 1, sqrt2 cos kx, sqrt2 sin kx)."""
    nubar = rng.uniform(*nu_range, n_a)
    nu_c = np.zeros((n_a, 2 * nu_modes + 1))
    nu_c[:, 0] = nubar
    nu_c[:, 1:] = nubar[:, None] * rng.uniform(-nu_amp, nu_amp, (n_a, 2 * nu_modes)) / np.sqrt(2)
    kl = np.concatenate([[0], np.repeat(np.arange(1, K + 1), 2)])
    f_c = f_amp * rng.standard_normal((n_a, 2 * K + 1)) / (1.0 + kl)
    return nubar, nu_c, f_c


def eval_coef(coef, m, kmax):
    R, _ = real_fourier_basis(m, kmax)
    return coef @ R.T


def sample_ic(rng, n, K, amp, m):
    kl = np.concatenate([[0], np.repeat(np.arange(1, K + 1), 2)])
    c = amp * rng.standard_normal((n, 2 * K + 1)) / (1.0 + kl)
    c[:, 0] *= 0.3
    return eval_coef(c, m, K)


def simulate(regime, nu_c, f_c, nu_modes, K, n_grid, n_ic, n_t, T_obs, amp, n_fine, rng):
    """Returns U, Ut of shape (n_a, n_ic*n_t, n_grid) on the n-grid; order = (ic, time)."""
    n_a = nu_c.shape[0]
    m = n_grid if regime == "closed" else n_fine
    kcut = K if regime == "closed" else m // 3                      # Galerkin cut / 2/3 dealiasing
    nu = eval_coef(nu_c, m, nu_modes)[:, None, :]                   # (n_a, 1, m)
    f = eval_coef(f_c, m, K)[:, None, :]
    u = sample_ic(rng, n_a * n_ic, K, amp, m).reshape(n_a, n_ic, m)
    P = (lambda G: lowpass_np(G, kcut))

    def rhs(u):
        ux = deriv_np(u)
        if regime == "closed":           # Galerkin system: exact products on the n-grid, then project to |k|<=K
            return P(-u * ux + deriv_np(nu * ux) + f)
        return P(-P(u * ux) + deriv_np(P(nu * ux)) + f)

    numax = float(np.max(nu))
    dt_stab = 2.0 / (numax * kcut ** 2 + 1e-12)
    dt_save = T_obs / n_t
    n_sub = int(np.ceil(dt_save / min(dt_stab, 0.01)))
    h = dt_save / n_sub
    Us, Uts = [], []
    for j in range(n_t):
        Us.append(u.copy()); Uts.append(rhs(u))
        if j == n_t - 1:
            break
        for _ in range(n_sub):
            k1 = rhs(u); k2 = rhs(u + h / 2 * k1); k3 = rhs(u + h / 2 * k2); k4 = rhs(u + h * k3)
            u = u + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
    U = np.stack(Us, 2)                                             # (n_a, n_ic, n_t, m)
    Ut = np.stack(Uts, 2)
    if regime != "closed":
        U, Ut = resample_np(U, n_grid), resample_np(Ut, n_grid)
    if not (np.all(np.isfinite(U)) and np.all(np.isfinite(Ut))):
        raise RuntimeError("simulation blew up")
    return U.reshape(n_a, n_ic * n_t, n_grid), Ut.reshape(n_a, n_ic * n_t, n_grid), dt_save


# ----------------------------------------------------------------------------- basis
def stacked_normalised(U, Ut):
    X = np.concatenate([U.reshape(-1, U.shape[-1]), Ut.reshape(-1, Ut.shape[-1])], 0)
    return X / (np.linalg.norm(X, axis=1, keepdims=True) + 1e-30)


def pod_of(X, r):
    _, s, Vt = np.linalg.svd(X, full_matrices=False)
    return Vt[:r].T * np.sqrt(X.shape[1]), s


def train_trunk(X, r, steps, lr, width, depth, seed, device, log):
    torch.manual_seed(seed)
    n = X.shape[1]
    tr = Trunk(r, width, depth).to(device)
    x = torch.linspace(0, 2 * np.pi, n + 1, dtype=torch.float64, device=device)[:-1]
    Xt = torch.tensor(X, device=device)
    opt = torch.optim.Adam(tr.parameters(), lr=lr)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, steps)
    g = torch.Generator().manual_seed(seed)
    for t in range(steps):
        idx = torch.randint(0, Xt.shape[0], (min(4096, Xt.shape[0]),), generator=g).to(device)
        Q, _ = torch.linalg.qr(tr(x))
        Xb = Xt[idx]
        res = Xb - (Xb @ Q) @ Q.T
        loss = (res ** 2).sum() / (Xb ** 2).sum()
        opt.zero_grad(); loss.backward(); opt.step(); sch.step()
        if t % max(1, steps // 5) == 0 or t == steps - 1:
            log(f"    [trunk] step {t}: span residual {loss.item():.3e}")
    with torch.no_grad():
        Q, _ = torch.linalg.qr(tr(x))
    return Q.cpu().numpy() * np.sqrt(n)


def span_residual(Phi, X):
    n = X.shape[1]
    Pr = (X @ Phi) @ Phi.T / n
    return float(np.sqrt(np.sum((X - Pr) ** 2) / np.sum(X ** 2)))


# ----------------------------------------------------------------------------- models
class MLP(torch.nn.Module):
    def __init__(self, d_in, d_out, width, depth, zero_last=True):
        super().__init__()
        layers, d = [], d_in
        for _ in range(depth):
            layers += [torch.nn.Linear(d, width), torch.nn.GELU()]; d = width
        last = torch.nn.Linear(d, d_out)
        if zero_last:
            torch.nn.init.zeros_(last.weight); torch.nn.init.zeros_(last.bias)
        self.net = torch.nn.Sequential(*layers, last)

    def forward(self, x):
        return self.net(x)


class Base(torch.nn.Module):
    """Common pieces: basis Phi (fixed), input standardisation, quadratic index sets."""

    def __init__(self, Phi, a_mean, a_std):
        super().__init__()
        self.n, self.r = Phi.shape
        self.register_buffer("Phi", torch.tensor(Phi))
        self.register_buffer("a_mean", torch.tensor(a_mean)); self.register_buffer("a_std", torch.tensor(a_std))
        P, Q = np.triu_indices(self.r)
        self.register_buffer("P", torch.tensor(P)); self.register_buffer("Q", torch.tensor(Q))

    def a_in(self, Araw):
        return (Araw - self.a_mean) / self.a_std


class TCO(Base):
    def __init__(self, Phi, a_mean, a_std, theta_bar, theta_scale, width, depth):
        super().__init__(Phi, a_mean, a_std)
        r, nq = self.r, self.P.numel()
        self.sizes = [r, r * r, r * nq]
        self.branch = MLP(a_mean.size, sum(self.sizes), width, depth)
        self.register_buffer("th0", torch.tensor(theta_bar)); self.register_buffer("ths", torch.tensor(theta_scale))

    def params(self, Araw):
        th = self.th0 + self.ths * self.branch(self.a_in(Araw))
        b, A, T = torch.split(th, self.sizes, -1)
        return b, A.reshape(-1, self.r, self.r), T.reshape(-1, self.r, self.P.numel())

    def rhs(self, Araw, C):
        b, A, T = self.params(Araw)
        q = C[:, self.P] * C[:, self.Q]
        return b + torch.einsum("bkj,bj->bk", A, C) + torch.einsum("bkq,bq->bk", T, q)


class DeepONet(Base):
    def __init__(self, Phi, a_mean, a_std, u_mean, u_std, d_mean, d_std, width, depth):
        super().__init__(Phi, a_mean, a_std)
        self.um, self.us = float(u_mean), float(u_std)
        self.branch = MLP(a_mean.size + self.n, self.r, width, depth)
        self.register_buffer("dm", torch.tensor(d_mean)); self.register_buffer("ds", torch.tensor(d_std))

    def rhs(self, Araw, C):
        U = C @ self.Phi.T
        return self.dm + self.ds * self.branch(torch.cat([self.a_in(Araw), (U - self.um) / self.us], -1))


class Galerkin(Base):
    """Exact Galerkin system on the given basis, same spectral derivative as the closed-data generator."""

    def rhs(self, Araw, C):
        n = self.n
        nu, f = Araw[:, :n], Araw[:, n:]
        u = C @ self.Phi.T
        ux = deriv_t(u)
        N = -u * ux + deriv_t(nu * ux) + f
        return N @ self.Phi / n


class OpInf(Base):
    """Parametric OpInf, affine in input coefficients; fitted by least squares on the same data."""

    def __init__(self, Phi, a_mean, a_std, Rnu, Rf):
        super().__init__(Phi, a_mean, a_std)
        self.register_buffer("Rnu", torch.tensor(Rnu)); self.register_buffer("Rf", torch.tensor(Rf))
        self.W = None

    def feats(self, Araw, C):
        n = self.n
        nh = Araw[:, :n] @ self.Rnu / n
        fh = Araw[:, n:] @ self.Rf / n
        one = torch.ones_like(C[:, :1])
        p1 = torch.cat([one, nh], 1)                                   # (B, 1+m)
        lin = (C[:, :, None] * p1[:, None, :]).flatten(1)
        q = C[:, self.P] * C[:, self.Q]
        quad = (q[:, :, None] * p1[:, None, :]).flatten(1)
        return torch.cat([one, nh, fh, lin, quad], 1)

    def fit(self, Araw, C, Dc, rcond=1e-10):
        X = self.feats(Araw, C).cpu().numpy()
        sc = np.sqrt((X ** 2).mean(0)) + 1e-14
        W = np.linalg.lstsq(X / sc, Dc.cpu().numpy(), rcond=rcond)[0] / sc[:, None]
        self.W = torch.tensor(W, device=C.device)
        return X.shape[1]

    def rhs(self, Araw, C):
        return self.feats(Araw, C) @ self.W


# ----------------------------------------------------------------------------- extraction / scoring
def extract_bAS(rhs, araw, cbar, eps):
    """(b, A, S) of a generator around cbar: g(c) ~ b + A c + S(c, c), S symmetric in its last two indices.
    Central differences + Richardson; exact (to round-off) for quadratic generators."""
    r = cbar.size
    I = np.eye(r)
    P, Q = np.triu_indices(r)
    V = np.concatenate([I, I[P] + I[Q]], 0)                           # r + r(r+1)/2 directions
    C = [cbar[None]]
    for e in (eps, eps / 2):
        C += [cbar + e * V, cbar - e * V]
    C = np.concatenate(C, 0)
    dev = araw.device
    with torch.no_grad():
        G = rhs(araw[None].expand(C.shape[0], -1), torch.tensor(C, device=dev)).cpu().numpy()
    g0, m = G[0], V.shape[0]
    Gp1, Gm1, Gp2, Gm2 = G[1:1 + m], G[1 + m:1 + 2 * m], G[1 + 2 * m:1 + 3 * m], G[1 + 3 * m:]
    Q1 = (Gp1 + Gm1 - 2 * g0) / (2 * eps ** 2)
    Q2 = (Gp2 + Gm2 - 2 * g0) / (2 * (eps / 2) ** 2)
    Qv = (4 * Q2 - Q1) / 3                                             # S(v, v) per direction
    L1 = (Gp1[:r] - Gm1[:r]) / (2 * eps)
    L2 = (Gp2[:r] - Gm2[:r]) / eps
    J = ((4 * L2 - L1) / 3).T                                          # (k, j)
    S = np.zeros((r, r, r))
    diag = Qv[:r]                                                      # (i, k)
    for i in range(r):
        S[:, i, i] = diag[i]
    pair = Qv[r:]
    off = P != Q
    vals = (pair[off] - diag[P[off]] - diag[Q[off]]) / 2
    S[:, P[off], Q[off]] = vals.T
    S[:, Q[off], P[off]] = vals.T
    A = J - 2 * np.einsum("kij,i->kj", S, cbar)
    b = g0 - A @ cbar - np.einsum("kij,i,j->k", S, cbar, cbar)
    return b, A, S


def rel(x, y):
    return float(np.linalg.norm(x - y) / (np.linalg.norm(y) + 1e-30))


def rollout(rhs, Araw, C0, n_t, dt_save, n_sub=20):
    """RK4 in coefficient space; returns C at the saved times (B, n_t, r) or None if it blows up."""
    with torch.no_grad():
        c = C0.clone(); out = [c.clone()]
        h = dt_save / n_sub
        for _ in range(1, n_t):
            for _ in range(n_sub):
                k1 = rhs(Araw, c); k2 = rhs(Araw, c + h / 2 * k1); k3 = rhs(Araw, c + h / 2 * k2)
                k4 = rhs(Araw, c + h * k3)
                c = c + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
                if not torch.all(torch.isfinite(c)):
                    return None
            out.append(c.clone())
    return torch.stack(out, 1)


def train_model(model, Araw_tr, C_tr, D_tr, ai, steps, lr, batch, log, tag):
    opt = torch.optim.Adam([p for p in model.parameters() if p.requires_grad], lr=lr)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, steps)
    g = torch.Generator().manual_seed(0)
    nd = (D_tr ** 2).sum(1).mean()
    for t in range(steps):
        idx = torch.randint(0, C_tr.shape[0], (min(batch, C_tr.shape[0]),), generator=g).to(C_tr.device)
        pred = model.rhs(Araw_tr[ai[idx]], C_tr[idx])
        loss = ((pred - D_tr[idx]) ** 2).sum(1).mean() / nd          # = field u_t loss (orthonormal trunk)
        opt.zero_grad(); loss.backward(); opt.step(); sch.step()
        if t % max(1, steps // 5) == 0 or t == steps - 1:
            log(f"    [{tag}] step {t}: u_t loss {loss.item():.3e}")


