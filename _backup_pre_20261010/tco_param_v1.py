#!/usr/bin/env python3
"""
TCO experiment 1 — input-dependent tensor on a learned basis (validation experiment).

PDE (periodic, x in [0, 2pi)):   u_t = -u u_x + (nu(x) u_x)_x + f(x)
Input function a = (nu(x), f(x)), drawn at random per input; several trajectories per input.
Task: the generator  (a, u) -> u_t.

Models (all share ONE trunk basis Phi, trained in stage 1 from data only; c = <u, Phi>):
  tco       branch MLP(a) -> (b(a), A(a), T(a));  dc/dt = b + A c + T(c, c)
  deeponet  MLP(a, u) -> dc/dt                     (vanilla DeepONet branch, same trunk)
  opinf     parametric Operator Inference, affine in input coefficients (least squares):
            b = b0 + B [nu_hat, f_hat],  A = A0 + sum_m nu_hat_m A_m,  T = T0 + sum_m nu_hat_m T_m
  galerkin  the exact Galerkin system ON THE SAME BASIS:  dc/dt = <N(Phi c), Phi>  (reference)

Training uses only (a, u, u_t). With a fixed orthonormal trunk the field loss ||u_t - Phi g||^2
equals the coefficient loss ||g - <u_t, Phi>||^2 + const, i.e. the Galerkin projection; models are
trained with this u_t loss only (no rollout loss).

Scoring (identical for every model; the truth is computed on the model's own basis, so it is
gauge-independent): one Taylor extractor reads (b, A, T) of any model's generator around the
input's state mean c_bar, and compares with the extracted Galerkin truth on the same basis.
  * b_rel, A_rel, T_rel                 per test input (median)
  * T_var    = mean_a ||T(a) - mean T|| / ||mean T||       truth: 0 (advection does not depend on a)
  * T_var_R2_nu: fraction of T's input variation explained linearly by mean viscosity
    (closed data: T should be constant; full data: closure may depend on nu -> report, not an error)
  * span residuals of test u and u_t on the basis (vs POD and Fourier at the same r)
  * cond([1, c]) per training input (identifiability of b vs A needs >= r+1 affinely independent states)
  * u_t test error (field), rollout error

Regimes: closed = data generated by the Galerkin-truncated system on the n-grid with the SAME spectral
derivative used for scoring (difference to truth should be ~0); full = fine-grid DNS (difference = closure).
  python tco_param.py --quick --out runs/P1_smoke
"""
