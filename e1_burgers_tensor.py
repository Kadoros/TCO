# Figures (reference palette: blue sequential ramp, categorical slots 1-2)
# ----------------------------------------------------------------------------
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK2 = "#52514e"
GRID = "#e4e3df"
SERIES = {"closed": "#2a78d6", "full": "#eb6834"}
SEQ = ["#fcfcfb", "#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]


def _style(ax):
    ax.set_facecolor(SURFACE)
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    for s in ["left", "bottom"]:
        ax.spines[s].set_color(INK2)
        ax.spines[s].set_linewidth(0.8)
    ax.tick_params(colors=INK2, labelsize=9)
    ax.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


def tensor_slice(T, K, k_show):
    modes, P, Q = pair_index(K)
    n = 2 * K + 1
    S = np.full((n, n), np.nan)
    row = list(modes).index(k_show)
    for col, (pi, qi) in enumerate(zip(P, Q)):
        S[pi, qi] = np.abs(T[row, col])
    return S


def fig_tensor(T_t, T_l_closed, T_l_full, K, k_show, nu, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    cmap = LinearSegmentedColormap.from_list("seq_blue", SEQ)
    cmap.set_bad(SURFACE)
    slices = [("True (Galerkin)", tensor_slice(T_t, K, k_show)),
              ("Learned, closed data", tensor_slice(T_l_closed, K, k_show)),
              (f"Learned, full data (nu={nu})", tensor_slice(T_l_full, K, k_show))]
    vmax = np.nanmax(slices[0][1])
    fig, axes = plt.subplots(1, 3, figsize=(12, 4.2), facecolor=SURFACE)
    modes = np.arange(-K, K + 1)
    for ax, (title, S) in zip(axes, slices):
        im = ax.imshow(S, cmap=cmap, vmin=0, vmax=vmax, origin="lower",
                       extent=[-K - .5, K + .5, -K - .5, K + .5])
        ax.plot(modes, k_show - modes, color=INK2, lw=0.8, ls="--")  # p+q=k line
        ax.set_xlim(-K - .5, K + .5); ax.set_ylim(-K - .5, K + .5)
        ax.set_title(title, color=INK, fontsize=11)
        ax.set_xlabel("q (mode index)", color=INK2, fontsize=9)
        ax.set_ylabel("p (mode index)", color=INK2, fontsize=9)
        ax.tick_params(colors=INK2, labelsize=8)
        for s in ax.spines.values():
            s.set_visible(False)
    cb = fig.colorbar(im, ax=axes, shrink=0.85, pad=0.02)
    cb.set_label(f"|T[k={k_show}, p, q]|", color=INK2, fontsize=9)
    cb.ax.tick_params(colors=INK2, labelsize=8)
    cb.outline.set_visible(False)
    fig.suptitle(f"Learned coupling for output mode k={k_show}; dashed = selection rule p+q=k",
                 color=INK, fontsize=12, x=0.02, ha="left")
    fig.savefig(path, dpi=160, facecolor=SURFACE, bbox_inches="tight")
    plt.close(fig)


def fig_sweep(results, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), facecolor=SURFACE)
    panels = [("rel_err_T", "Relative tensor error ||T_learned - T_true|| / ||T_true||", True),
              ("selection_mass", "Fraction of |T| on selection rule p+q=k", False)]
    for ax, (key, title, logy) in zip(axes, panels):
        _style(ax)
        for regime, label in [("closed", "Closed data"), ("full", "Full (truncated) data")]:
            rows = sorted([r for r in results if r["regime"] == regime], key=lambda r: r["nu"])
            if not rows:
                continue
            x = [r["nu"] for r in rows]
            y = [r["metrics"][key] for r in rows]
            ax.plot(x, y, color=SERIES[regime], lw=2, marker="o", ms=6,
                    markeredgecolor=SURFACE, markeredgewidth=1.5, label=label)
            dy = -14 if (not logy and y[0] > 0.9) else 6
            ax.annotate(label, (x[0], y[0]), xytext=(6, dy), textcoords="offset points",
                        color=INK2, fontsize=8)
        ax.set_xscale("log")
        if logy:
            ax.set_yscale("log")
        else:
            ax.set_ylim(0, 1.02)
        ax.set_xlabel("viscosity nu (smaller = more energy beyond K)", color=INK2, fontsize=9)
        ax.set_title(title, color=INK, fontsize=10, loc="left")
    axes[0].legend(frameon=False, fontsize=9, labelcolor=INK2)
    fig.savefig(path, dpi=160, facecolor=SURFACE, bbox_inches="tight")
    plt.close(fig)


# ----------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--K", type=int, default=8, help="number of learned modes (|k|<=K)")
    ap.add_argument("--kmax_full", type=int, default=128, help="solver resolution for 'full' regime")
    ap.add_argument("--nus", type=float, nargs="+", default=[0.5, 0.2, 0.1, 0.05, 0.02])
    ap.add_argument("--regimes", nargs="+", default=["closed", "full"])
    ap.add_argument("--n_traj", type=int, default=200)
    ap.add_argument("--n_test", type=int, default=40)
    ap.add_argument("--t_final", type=float, default=2.0)
    ap.add_argument("--dt", type=float, default=1e-3)
    ap.add_argument("--save_every", type=int, default=20)
    ap.add_argument("--amp", type=float, default=1.0, help="max|u| of initial condition")
    ap.add_argument("--mean_amp", type=float, default=0.5,
                    help="random mean in U(-a,a); 0 makes mode-0 triads unidentifiable")
    ap.add_argument("--kmax_ic", type=int, default=None, help="IC bandwidth (default K)")
    ap.add_argument("--ridge", type=float, default=1e-10)
    ap.add_argument("--method", choices=["lstsq", "stlsq"], default="lstsq")
    ap.add_argument("--stlsq_thresh", type=float, default=0.02)
    ap.add_argument("--stlsq_iter", type=int, default=5)
    ap.add_argument("--noise", type=float, default=0.0, help="relative Gaussian noise on z and dz/dt")
    ap.add_argument("--k_show", type=int, default=3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--quick", action="store_true", help="tiny smoke-test settings")
    ap.add_argument("--out", default="runs/e1")
    a = ap.parse_args()

    if a.quick:
        a.n_traj, a.n_test, a.t_final, a.nus, a.kmax_full = 40, 10, 0.5, [0.2, 0.05], 48
    kmax_ic = a.kmax_ic or a.K
    os.makedirs(a.out, exist_ok=True)
    logf = open(os.path.join(a.out, "log.txt"), "w")

    def log(*m):
        s = " ".join(str(x) for x in m)
        print(s, flush=True)
        logf.write(s + "\n")

    log("args:", json.dumps(vars(a)))
    results, keep = [], {}
    for nu in a.nus:
        A_t, T_t = true_operators(a.K, nu)
        for regime in a.regimes:
            t0 = time.time()
            kmax_solver = a.K if regime == "closed" else a.kmax_full
            rng = np.random.default_rng(a.seed)
            Z, dZ, _ = simulate(nu, kmax_solver, a.K, a.n_traj, a.t_final, a.dt,
                                a.save_every, rng, a.amp, kmax_ic, a.mean_amp)
            rng_te = np.random.default_rng(a.seed + 10_000)
            Zte, dZte, tid = simulate(nu, kmax_solver, a.K, a.n_test, a.t_final, a.dt,
                                      a.save_every, rng_te, a.amp, kmax_ic, a.mean_amp)
            if a.noise > 0:
                nr = np.random.default_rng(a.seed + 1)
                for X in (Z, dZ):
                    s = a.noise * np.sqrt(np.mean(np.abs(X) ** 2))
                    X += s * (nr.standard_normal(X.shape) + 1j * nr.standard_normal(X.shape)) / np.sqrt(2)
            A_l, T_l = fit(Z, dZ, a.K, a.ridge, a.method, a.stlsq_thresh, a.stlsq_iter)
            m = metrics(A_l, T_l, A_t, T_t, a.K, Zte, dZte)
            first = Zte[tid == 0]
            m["rollout_rel_err_final"] = rollout_error(A_l, T_l, a.K, first[0], first,
                                                      a.dt * a.save_every)[-1]
            m["n_samples"] = int(Z.shape[0])
            m["n_features"] = int(features(Z[:1], a.K).shape[1])
            log(f"[nu={nu:<5} {regime:<6}] relT={m['rel_err_T']:.2e} relT_rule={m['rel_err_T_on_rule']:.2e} sel={m['selection_mass']:.3f} "
                f"offRule={m['max_off_rule_ratio']:.2e} Ediag={m['rel_err_A_diag']:.2e} "
                f"Eviol={m['energy_violation']:.2e} test_dz={m['test_rel_err_dzdt']:.2e} "
                f"rollout={m['rollout_rel_err_final']:.2e}  ({time.time()-t0:.1f}s)")
            results.append({"nu": nu, "regime": regime, "metrics": m})
            keep[(nu, regime)] = T_l

    with open(os.path.join(a.out, "results.json"), "w") as f:
        json.dump({"args": vars(a), "results": results}, f, indent=2)

    # figures
    nu_show = min(a.nus)
    if ("closed" in a.regimes) and ("full" in a.regimes):
        _, T_t = true_operators(a.K, nu_show)
        fig_tensor(T_t, keep[(nu_show, "closed")], keep[(nu_show, "full")], a.K, a.k_show,
                   nu_show, os.path.join(a.out, f"fig_tensor_k{a.k_show}.png"))
    fig_sweep(results, os.path.join(a.out, "fig_nu_sweep.png"))
    log("saved to", a.out)


if __name__ == "__main__":
    main()
