#!/usr/bin/env python3
"""
TCO E1 — Can a 3rd-order coupling tensor learned from data recover the true
triadic interaction tensor of 1D viscous Burgers?

PDE (periodic, x in [0, 2pi)):   u_t + u u_x = nu u_xx
Fourier:  u = sum_k c_k e^{ikx},  c_{-k} = conj(c_k)
Exact modal dynamics:
    dc_k/dt = -nu k^2 c_k  - (i k / 2) * sum_{p+q=k} c_p c_q

Learned model on the first K modes (state z = [c_{-K}, ..., c_K], complex):
    dz_k/dt = sum_j A_kj z_j + sum_{p<=q} T_k,(p,q) z_p z_q
Canonical (symmetrized) true tensor on unordered pairs p<=q:
    T_true[k,(p,q)] = -i k        if p+q=k and p<q
                    = -i k / 2    if p+q=k and p=q
                    = 0           otherwise
    A_true = diag(-nu k^2)

Two data regimes:
  closed : data generated by the K-mode Galerkin system itself
           -> identifiability sanity check (should recover T almost exactly)
  full   : data from a high-resolution solver, projected onto K modes
           -> closure (truncated modes) contaminates the learned tensor;
              contamination should grow as nu decreases

Outputs (in --out):
  results.json                 all metrics per (regime, nu)
  fig_tensor_k{K_SHOW}.png     |T| slice for one output mode: true vs learned
  fig_nu_sweep.png             tensor error and selection-rule mass vs nu
  log.txt                      console log

Only numpy + matplotlib. Example:
  python e1_burgers_tensor.py --out runs/e1_default
  python e1_burgers_tensor.py --quick --out runs/e1_smoke     # ~1 min smoke test
"""
import argparse
import json
import os
import time

import numpy as np


# ----------------------------------------------------------------------------
# Spectral Burgers solver (exactly dealiased Galerkin truncation at |k|<=kmax)
# ----------------------------------------------------------------------------
class BurgersSpectral:
    """State = rfft coefficients normalised so u(x) = sum_k c_k e^{ikx}.
    Nonlinear term is computed on a grid with M >= 3*kmax+1 points, which makes
    the truncated quadratic term exact (no aliasing) = exact Galerkin system."""

    def __init__(self, nu, kmax):
        self.nu = nu
        self.kmax = kmax
        self.M = int(2 ** np.ceil(np.log2(3 * kmax + 2)))  # >= 3 kmax + 1
        self.k = np.arange(self.M // 2 + 1)
        self.mask = (self.k <= kmax).astype(float)
        self.lin = -nu * self.k ** 2

    def to_grid(self, c):
        return np.fft.irfft(c * self.M, n=self.M)

    def nonlinear(self, c):
        u = self.to_grid(c)
        uu = np.fft.rfft(u * u) / self.M
        return (-0.5j * self.k * uu) * self.mask

    def rhs(self, c):
        return self.lin * c + self.nonlinear(c)

    def step_ifrk4(self, c, dt):
        """Integrating-factor RK4 (Trefethen)."""
        E = np.exp(self.lin * dt)
        E2 = np.exp(self.lin * dt / 2)
        a = dt * self.nonlinear(c)
        b = dt * self.nonlinear(E2 * (c + a / 2))
        d_ = dt * self.nonlinear(E2 * c + b / 2)
        e = dt * self.nonlinear(E * c + E2 * d_)
        return E * c + (E * a + 2 * E2 * (b + d_) + e) / 6.0


def random_ic(rng, kmax_ic, n_pad_k, amp, mean_amp):
    """Random real field: c_k ~ k^-1 * random phase for 1<=k<=kmax_ic, plus a
    random mean c_0 ~ U(-mean_amp, mean_amp). The mean must vary across
    trajectories, otherwise triads involving mode 0 are NOT identifiable
    (Burgers conserves the mean, so z_0 * z_p features would be identically 0)."""
    c = np.zeros(n_pad_k, dtype=complex)
    ks = np.arange(1, kmax_ic + 1)
    mag = rng.uniform(0.5, 1.5, size=ks.size) / ks
    ph = rng.uniform(0, 2 * np.pi, size=ks.size)
    c[1:kmax_ic + 1] = mag * np.exp(1j * ph)
    # normalise so max|u| ~ amp
    M = 2 * (n_pad_k - 1)
    u = np.fft.irfft(c * M, n=M)
    c *= amp / (np.max(np.abs(u)) + 1e-12)
    c[0] = rng.uniform(-mean_amp, mean_amp)
    return c


def rfft_to_state(c, K):
    """rfft coeffs (k>=0) -> z = [c_{-K},...,c_K]."""
    pos = c[:K + 1]
    neg = np.conj(pos[1:][::-1])
    return np.concatenate([neg, pos])


def simulate(nu, kmax_solver, K, n_traj, t_final, dt, save_every, rng,
             amp, kmax_ic, mean_amp):
    """Returns Z (snapshots, 2K+1) and dZ (exact time derivative of the
    projected coefficients = projection of the solver's RHS)."""
    sol = BurgersSpectral(nu, kmax_solver)
    nk = sol.M // 2 + 1
    Zs, dZs, traj_id = [], [], []
    n_steps = int(round(t_final / dt))
    for tr in range(n_traj):
        c = random_ic(rng, min(kmax_ic, kmax_solver), nk, amp, mean_amp)
        c *= sol.mask
        for s in range(n_steps + 1):
            if s % save_every == 0:
                Zs.append(rfft_to_state(c, K))
                dZs.append(rfft_to_state(sol.rhs(c), K))
                traj_id.append(tr)
            if s < n_steps:
                c = sol.step_ifrk4(c, dt)
                if not np.all(np.isfinite(c)):
                    raise RuntimeError(f"solver blew up (nu={nu}); lower dt")
    return np.array(Zs), np.array(dZs), np.array(traj_id)


# ----------------------------------------------------------------------------
# Regression: dz/dt = A z + T (z ⊗ z)_{p<=q}
# ----------------------------------------------------------------------------
def pair_index(K):
    modes = np.arange(-K, K + 1)
    P, Q = np.triu_indices(2 * K + 1)          # p<=q as array indices
    return modes, P, Q


def features(Z, K):
    _, P, Q = pair_index(K)
    return np.concatenate([Z, Z[:, P] * Z[:, Q]], axis=1)


def true_operators(K, nu):
    modes, P, Q = pair_index(K)
    n = 2 * K + 1
    A = np.diag(-nu * modes.astype(float) ** 2).astype(complex)
    T = np.zeros((n, P.size), dtype=complex)
    p, q = modes[P], modes[Q]
    for i, k in enumerate(modes):
        sel = (p + q == k)
        T[i, sel] = np.where(p[sel] < q[sel], -1j * k, -0.5j * k)
    return A, T


def fit(Z, dZ, K, ridge, method, stlsq_thresh, stlsq_iter):
    Phi = features(Z, K)
    n = 2 * K + 1
    # column scaling for conditioning
    scale = np.sqrt(np.mean(np.abs(Phi) ** 2, axis=0)) + 1e-14
    X = Phi / scale
    F = X.shape[1]
    G = X.conj().T @ X + ridge * np.eye(F)
    W = np.linalg.solve(G, X.conj().T @ dZ)          # (F, n)
    if method == "stlsq":                            # sequential thresholded LS
        for _ in range(stlsq_iter):
            Wd = W / scale[:, None]
            small = np.abs(Wd) < stlsq_thresh * np.max(np.abs(Wd), axis=0, keepdims=True)
            W[small] = 0
            for j in range(n):
                keep = ~small[:, j]
                if keep.sum() == 0:
                    continue
                Xs = X[:, keep]
                Gs = Xs.conj().T @ Xs + ridge * np.eye(keep.sum())
                W[keep, j] = np.linalg.solve(Gs, Xs.conj().T @ dZ[:, j])
    W = W / scale[:, None]
    A = W[:n, :].T
    T = W[n:, :].T
    return A, T


# ----------------------------------------------------------------------------
# Metrics
# ----------------------------------------------------------------------------
def metrics(A_l, T_l, A_t, T_t, K, Z_test, dZ_test):
    modes, P, Q = pair_index(K)
    p, q = modes[P], modes[Q]
    sel = (p[None, :] + q[None, :] == modes[:, None])            # (n, pairs)
    absT = np.abs(T_l)
    out = {
        "rel_err_T": float(np.linalg.norm(T_l - T_t) / np.linalg.norm(T_t)),
        "rel_err_A_diag": float(np.linalg.norm(np.diag(A_l) - np.diag(A_t))
                                / (np.linalg.norm(np.diag(A_t)) + 1e-14)),
        "offdiag_A_ratio": float(np.linalg.norm(A_l - np.diag(np.diag(A_l)))
                                 / (np.linalg.norm(np.diag(A_l)) + 1e-14)),
        # error restricted to entries ON the selection rule (are the true triads right?)
        "rel_err_T_on_rule": float(np.linalg.norm((T_l - T_t)[sel]) / np.linalg.norm(T_t[sel])),
        # fraction of |T| mass on the true selection rule p+q=k
        "selection_mass": float(absT[sel].sum() / (absT.sum() + 1e-14)),
        # largest |T| entry off the selection rule, relative to largest on it
        "max_off_rule_ratio": float(absT[~sel].max() / (absT[sel].max() + 1e-14)),
    }
    # energy conservation of the learned quadratic part:
    # true triads satisfy Re(sum_k conj(z_k) N_k(z)) = 0 for real fields
    _, Pp, Qq = pair_index(K)
    N = (Z_test[:, Pp] * Z_test[:, Qq]) @ T_l.T
    num = np.abs(np.real(np.sum(np.conj(Z_test) * N, axis=1)))
    den = np.sqrt(np.sum(np.abs(Z_test) ** 2, axis=1)) * np.sqrt(np.sum(np.abs(N) ** 2, axis=1)) + 1e-14
    out["energy_violation"] = float(np.mean(num / den))
    # one-step derivative fit on held-out data
    pred = Z_test @ A_l.T + (Z_test[:, Pp] * Z_test[:, Qq]) @ T_l.T
    out["test_rel_err_dzdt"] = float(np.linalg.norm(pred - dZ_test) / np.linalg.norm(dZ_test))
    return out


def rollout_error(A_l, T_l, K, Z0, Z_ref, dt_save):
    """RK4 rollout of the learned ODE from Z0; compare to reference snapshots."""
    _, P, Q = pair_index(K)

    def f(z):
        return A_l @ z + T_l @ (z[P] * z[Q])

    n_sub = 10
    h = dt_save / n_sub
    z = Z0.copy()
    errs = [0.0]
    for t in range(1, Z_ref.shape[0]):
        for _ in range(n_sub):
            k1 = f(z); k2 = f(z + h / 2 * k1); k3 = f(z + h / 2 * k2); k4 = f(z + h * k3)
            z = z + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        if not np.all(np.isfinite(z)) or np.linalg.norm(z) > 1e6:
            errs.append(float("inf"))
            break
        errs.append(float(np.linalg.norm(z - Z_ref[t]) / (np.linalg.norm(Z_ref[t]) + 1e-14)))
    return errs


